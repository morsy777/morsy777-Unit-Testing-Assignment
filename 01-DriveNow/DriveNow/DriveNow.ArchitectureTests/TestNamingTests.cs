using NetArchTest.Rules;
using Shouldly;
using System.Reflection;
using System.Runtime.CompilerServices;
using System.Text.RegularExpressions;

namespace DriveNow.ArchitectureTests;

public class TestNamingTests
{
    [Fact]
    public void TestClasses_ShouldEndWithTests()
    {
        var assembly = Assembly.Load(ProjectNames.UintTestProjectName);

        var result = Types.InAssembly(assembly)
            .That()
            .AreClasses()
            .And()
            .ResideInNamespace(ProjectNames.UintTestNameSpace)
            .And()
            .DoNotHaveName(ProjectNames.AutoGeneratedProgram)
            .Should()
            .HaveNameEndingWith(ProjectNames.Tests)
            .GetResult();

        var message = "";

        foreach (var type in result.FailingTypes ?? [])
        {
            message += type.FullName + Environment.NewLine;
        }

        result.IsSuccessful.ShouldBeTrue(message);

        //result.IsSuccessful.ShouldBeTrue();
    }

    [Fact]
    public void TestMethods_ShouldMatchNamingPattern()
    {
        var assembly = Assembly.Load(ProjectNames.UintTestProjectName);

        var result = Types.InAssembly(assembly)
            .That()
            .DoNotHaveName(ProjectNames.AutoGeneratedProgram)
            .And()
            .DoNotHaveNameEndingWith("Faker"); 

        foreach (var type in result.GetTypes())
        {
            var methods = type.GetMethods(
                BindingFlags.Public |
                BindingFlags.NonPublic |
                BindingFlags.Instance |
                BindingFlags.Static |
                BindingFlags.DeclaredOnly);

            foreach (var method in methods)
            {
                if(method.IsDefined(typeof(CompilerGeneratedAttribute), false))
                    continue; // Skip compiler-generated methods

                if (method.IsSpecialName)
                    continue;

                var isTestMethod = method.IsDefined(typeof(FactAttribute), false) || 
                    method.IsDefined(typeof(TheoryAttribute), false);

                if (!isTestMethod)
                    continue;

                bool matchesPattern = Regex.IsMatch(method.Name, @"^[A-Za-z0-9]+_[A-Za-z0-9]+_[A-Za-z0-9]+$");

                matchesPattern.ShouldBeTrue($"{type.Name}.{method.Name} does not match the naming pattern.");
            }
        }
    }
}
